/**
 * Returns the canonical fixing state of a planet at the given (gate, line).
 * Returns null if no fixing is defined (most positions have none) or if the
 * planet isn't in the lookup table (Earth, Nodes, Moon nodes derivatives).
 */
export function lookupFixingState(
  planet: string,
  gate: number,
  line: number,
): FixingStateValue {
  const table = PLANET_FIXINGS[planet];
  if (!table) return null;
  return table[`${gate}.${line}`] ?? null;
}
